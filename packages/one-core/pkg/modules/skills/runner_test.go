package skills

import (
	"context"
	"os/exec"
	"testing"
)

func TestHashMatchesUpstreamPathOrdering(t *testing.T) {
	// The legacy digest was generated with this locale. Version 1 follows
	// the upstream environment locale; version 2 is locale-independent.
	t.Setenv("LC_ALL", "C")
	t.Setenv("LANG", "C")
	if _, err := exec.LookPath("node"); err != nil {
		t.Skip("Node is unavailable")
	}
	files := Files{
		"SKILL.md":            []byte("guidance\n"),
		"references/a.md":     []byte("a\n"),
		"references/Z.md":     []byte("Z\n"),
		"references/_note.md": []byte("note\n"),
		"references/中文.md":    []byte("中文\n"),
	}
	// Digests generated by the upstream v1 legacy and v2 portable hashers.
	for _, test := range []struct {
		name, expected string
		version        int
	}{
		{"legacy", "5ca0c2ce3acd873d899879f864f0f7aca9632b0be6e97f5db8c357f43e5c10eb", 1},
		{"portable", "19129a64d6bc6f75e651b3b4bad9f3e92970f42d1650d2db2b5fa44f66c964f3", 2},
	} {
		t.Run(test.name, func(t *testing.T) {
			hashes, err := (Runner{}).Hash(context.Background(), t.TempDir(), map[string]Files{"one-cli": files}, test.version)
			if err != nil {
				t.Fatal(err)
			}
			if hashes["one-cli"] != test.expected {
				t.Fatalf("hash = %s, want %s", hashes["one-cli"], test.expected)
			}
		})
	}
}

func TestPortableHashMatchesUpstreamFilesAndLineEndings(t *testing.T) {
	if _, err := exec.LookPath("node"); err != nil {
		t.Skip("Node is unavailable")
	}
	for _, ending := range []string{"\n", "\r\n"} {
		t.Run(ending, func(t *testing.T) {
			files := Files{
				"SKILL.md":                     []byte("---" + ending + "name: fixture" + ending + "---" + ending),
				"references/中文.md":             []byte("中文" + ending),
				"assets/binary.bin":            {0, 13, 10, 255},
				"metadata.json":                []byte("ignore"),
				"references/metadata.json":     []byte("ignore nested"),
				".git/config":                  []byte("ignore git"),
				"__pycache__/compiled.pyc":     []byte("ignore cache"),
				"__pypackages__/dependency.py": []byte("ignore packages"),
				"node_modules/keep.js":         []byte("kept by v2" + ending),
			}
			hashes, err := (Runner{}).Hash(context.Background(), t.TempDir(), map[string]Files{"fixture": files}, 2)
			if err != nil {
				t.Fatal(err)
			}
			// Generated using skills@1.8.1/src/skill-hash.ts on this fixture.
			const expected = "87b75fa2f6717482b36de9bf9b029f02ebbff2dce0ed377f48b6e916e0ad6e19"
			if hashes["fixture"] != expected {
				t.Fatalf("portable hash = %s, want %s", hashes["fixture"], expected)
			}
		})
	}
}
